def test_trace_no_sensitive_data_exposure() -> None:
    """Verify that raw sensitive application values are not dumped verbatim into reasons."""
    config = {
        "rules": [
            {
                "rule_id": "MIN_CREDIT_SCORE",
                "category": "threshold",
                "field": "credit_score",
                "operator": "gte",
                "threshold": 650,
            }
        ]
    }
    secret_value = 540
    app_data = {
        "credit_score": secret_value,
        "ssn": "000-12-3456",
        "private_api_key": "sec_abc123xyz",
    }

    decision = evaluate_rules(config, app_data)

    income_result = decision.results[0]
    # The reason should explain the rule threshold rather than printing raw secret dictionaries
    assert "000-12-3456" not in income_result.reason
    assert "sec_abc123xyz" not in income_result.reason
    assert "credit_score" in income_result.reason
    assert "650" in income_result.reason


def test_decision_trace_conditional_implication_metadata() -> None:
    """Verify traces generated by conditional rules indicate branch evaluation."""
    config = {
        "rules": [
            {
                "rule_id": "SALARY_PROOF",
                "category": "conditional",
                "when": {"field": "type", "operator": "eq", "value": "A"},
                "then": {"field": "val", "operator": "gt", "value": 10},
            }
        ]
    }

    # When branch true, then branch evaluated
    d1 = evaluate_rules(config, {"type": "A", "val": 5})
    t1 = d1.results[0].trace
    assert t1 is not None
    assert t1["precondition_met"] is True
    assert t1["then_evaluated"] is True
    assert t1["passed"] is False

    # When branch false, then branch skipped
    d2 = evaluate_rules(config, {"type": "B"})
    t2 = d2.results[0].trace
    assert t2 is not None
    assert t2["precondition_met"] is False
    assert t2["then_evaluated"] is False
    assert t2["passed"] is True


def test_decision_result_serialization() -> None:
    """Verify that DecisionResult cleanly serializes to dict and JSON."""
    config = {
        "rules": [
            {
                "rule_id": "RULE_1",
                "category": "mandatory",
                "field": "user_id",
            }
        ]
    }
    decision = evaluate_rules(config, {"user_id": "usr_999"})

    # Test model_dump()
    dumped = decision.model_dump()
    assert dumped["status"] == "approved"
    assert dumped["passed"] is True
    assert dumped["total_rules"] == 1
    assert dumped["results"][0]["rule_id"] == "RULE_1"

    # Test JSON serialization
    json_str = decision.model_dump_json()
    assert '"status":"approved"' in json_str or '"status": "approved"' in json_str
    assert '"rule_id":"RULE_1"' in json_str or '"rule_id": "RULE_1"' in json_str


def test_decision_trace_group_combinator_details() -> None:
    """Verify that GroupRule traces detail child conditions and the combinator."""
    config = {
        "rules": [
            {
                "rule_id": "MULTI_CRITERIA",
                "category": "group",
                "combinator": "AND",
                "conditions": [
                    {"field": "age", "operator": "gte", "value": 21},
                    {"field": "country", "operator": "in", "value": ["US", "UK"]},
                ],
            }
        ]
    }
    decision = evaluate_rules(config, {"age": 25, "country": "FR"})

    assert decision.status == "rejected"
    group_res = decision.results[0]
    assert group_res.trace is not None
    assert group_res.trace["combinator"] == "AND"
    assert group_res.trace["passed"] is False
    assert len(group_res.trace["details"]["traces"]) == 2

