"""Tests for decision traces, evaluation metadata, and privacy preservation."""

from app.rules.evaluator import evaluate_rules


def test_decision_trace_structure_and_completeness() -> None:
    """Verify that decision results provide complete structural traces and counts."""
    config = {
        "version": "2.1",
        "description": "Risk Assessment Config",
        "rules": [
            {
                "rule_id": "AGE_MINIMUM",
                "category": "threshold",
                "field": "applicant_age",
                "operator": "gte",
                "threshold": 18,
            },
            {
                "rule_id": "INCOME_MINIMUM",
                "category": "threshold",
                "field": "annual_income",
                "operator": "gte",
                "threshold": 300000,
            },
        ],
    }
    app_data = {
        "applicant_age": 25,
        "annual_income": 200000,  # Below threshold
    }

    decision = evaluate_rules(config, app_data)

    # Validate overall structure
    assert decision.status == "rejected"
    assert decision.passed is False
    assert decision.total_rules == 2
    assert decision.passed_rules == 1
    assert decision.failed_rules == 1

    # Validate individual results
    age_res = decision.results[0]
    assert age_res.rule_id == "AGE_MINIMUM"
    assert age_res.category == "threshold"
    assert age_res.passed is True
    assert age_res.field == "applicant_age"
    assert age_res.operator == "gte"
    assert age_res.expected_value == 18
    assert age_res.trace is not None
    assert age_res.trace["rule_id"] == "AGE_MINIMUM"

    income_res = decision.results[1]
    assert income_res.rule_id == "INCOME_MINIMUM"
    assert income_res.category == "threshold"
    assert income_res.passed is False
    assert income_res.field == "annual_income"
    assert income_res.operator == "gte"
    assert income_res.expected_value == 300000


